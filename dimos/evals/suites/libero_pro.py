"""Every LIBERO-PRO task as a dimos eval, loaded from the pinned checkout's BDDL files.

One case per task in each LIBERO-PRO set, tagged with the set's folder name:

- ``bddl_files/<folder>``: the LIBERO suites (``libero_goal``, ``libero_spatial``,
  ``libero_object``, ``libero_10``, ``libero_90``) and LIBERO-PRO's prebuilt perturbation
  folders (``libero_goal_with_mug``, ``libero_object_temp_x0.3``, ...);
- ``<suite>_env|_swap|_object|_lan|_task``: LIBERO-PRO's YAML perturbations of the four
  benchmark suites, generated by its own perturbator (seed 0).

    dimos evals run dimos.evals.suites.libero_pro --agent dimos.evals.agents.pi --tags libero_goal_lan

LIBERO itself runs each task live with its own Panda (``panda-libero-sim``), starting from
LIBERO's recorded initial states where the task has them, and judges it with its own goal
check. The first import clones LIBERO-PRO (~1 GB) into the dimos cache.
Tasks the pinned LIBERO-PRO cannot build are left out: those needing objects it never
published, and ``BROKEN_UPSTREAM``.
"""

from __future__ import annotations

from pathlib import Path

from dimos.evals.environments.libero import LiberoEnvironment, libero_success
from dimos.evals.suites.mujoco_xarm import PERCEPTION_MODULES
from dimos.evals.suites.robosuite import GUIDANCE
from dimos.evals.types import EvalCase, Suite
from dimos.simulation.libero.benchmark import (
    PERTURBATIONS,
    UNAVAILABLE_OBJECTS,
    bddl_language,
    bddl_object_types,
    bddl_root,
    perturbed_bddl,
)

BENCHMARK_SUITES = ("libero_goal", "libero_spatial", "libero_object", "libero_10")
_SPATIAL_TASK = "libero_spatial_task.pick_up_the_black_bowl_on_the"
# Case id -> why LIBERO itself fails to build the task at the pinned commit.
BROKEN_UPSTREAM = {
    **dict.fromkeys(
        (
            f"libero_goal_object.{task}"
            for task in (
                "open_the_top_drawer_and_put_the_bowl_inside",
                "put_the_bowl_on_the_plate",
                "put_the_bowl_on_the_stove",
                "put_the_bowl_on_top_of_the_cabinet",
                "put_the_cream_cheese_in_the_bowl",
            )
        ),
        "ood_object.yaml substitutes red_bowl, which LIBERO does not register",
    ),
    "libero_10_object.LIVING_ROOM_SCENE5_put_the_white_mug_on_the_left_plate_and_put_the_yellow_and_white_mug_on_the_right_plate": (
        "ood_object.yaml substitutes white_white_porcelain_mug, which LIBERO does not register"
    ),
    **dict.fromkeys(
        (
            "libero_10_task.KITCHEN_SCENE3_turn_on_the_stove_and_put_the_moka_pot_on_it",
            f"{_SPATIAL_TASK}_cookie_box_and_place_it_on_the_plate",
            f"{_SPATIAL_TASK}_stove_and_place_it_on_the_plate",
        ),
        "ood_task.yaml's replacement goal is malformed BDDL",
    ),
    **dict.fromkeys(
        (
            "libero_10_with_milk.FLOOR_SCENE1_put_both_the_alphabet_soup_and_the_tomato_sauce_in_the_basket",
            "libero_10_with_milk.FLOOR_SCENE1_put_both_the_cream_cheese_box_and_the_butter_in_the_basket",
        ),
        "the BDDL places milk_1 twice",
    ),
    "libero_object_temp_y0.5.pick_up_the_cream_cheese_and_place_it_in_the_basket": (
        "LIBERO cannot place the shifted objects without overlap"
    ),
}


def case(folder: str, bddl: Path) -> EvalCase:
    base = next((s for s in ("libero_90", *BENCHMARK_SUITES) if folder.startswith(s)), folder)
    return EvalCase(
        id=f"{folder}.{bddl.stem}",
        inputs=f"{bddl_language(bddl).capitalize()}. {GUIDANCE}",
        environment=LiberoEnvironment(disable=PERCEPTION_MODULES, bddl=bddl),
        grade=libero_success,
        timeout_s=900.0,
        tags=frozenset({"mujoco", "libero_pro", "manipulation", folder, base}),
    )


def cases() -> list[EvalCase]:
    out = []
    for folder in sorted(p for p in bddl_root().iterdir() if p.is_dir()):
        for bddl in sorted(folder.glob("*.bddl")):
            if not bddl_object_types(bddl) & UNAVAILABLE_OBJECTS:
                out.append(case(folder.name, bddl))
    for suite in BENCHMARK_SUITES:
        for kind in PERTURBATIONS:
            for bddl in sorted((bddl_root() / suite).glob("*.bddl")):
                perturbed = perturbed_bddl(bddl, suite, kind)
                if perturbed.read_text() != bddl.read_text():
                    out.append(case(f"{suite}_{kind}", perturbed))
    return [c for c in out if c.id not in BROKEN_UPSTREAM]


SUITE: Suite = cases()
