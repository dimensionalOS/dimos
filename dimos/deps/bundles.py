"""Dependency bundle assignments for the built-in blueprints and modules.

``bundles.json`` maps each runtime bundle (an aggregate extra declared in ``pyproject.toml``)
to the registry names it covers. It is generated by ``test_all_blueprints_generation.py``
from the ``DEPENDENCY_BUNDLE`` literals (a file's own, else the nearest directory's
``dependency_bundle.py``). This module only reverses that mapping. It imports no blueprint code, so it works before any
optional package is installed.
"""

from __future__ import annotations

from collections.abc import Iterable
import difflib
import json
from pathlib import Path

from dimos.robot.all_blueprints import all_blueprints, all_modules

BUNDLES_PATH = Path(__file__).with_name("bundles.json")
LOCKS_DIR = Path(__file__).with_name("locks")


class BundleMetadataError(Exception):
    """``bundles.json`` is missing, malformed, or does not cover a registered name."""


class UnknownNameError(ValueError):
    """A requested name is not a built-in blueprint or module."""


def _reject_duplicate_keys(pairs: list[tuple[str, object]]) -> dict[str, object]:
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise BundleMetadataError(f"{BUNDLES_PATH}: duplicate key {key!r}")
        result[key] = value
    return result


def load_assignments(path: Path = BUNDLES_PATH) -> dict[str, str]:
    """Return name -> bundle after validating the literal structure of ``bundles.json``."""
    try:
        raw = json.loads(path.read_text(), object_pairs_hook=_reject_duplicate_keys)
    except FileNotFoundError as e:
        raise BundleMetadataError(f"bundle metadata is missing: {path}") from e
    except json.JSONDecodeError as e:
        raise BundleMetadataError(f"{path} is not valid JSON: {e}") from e
    if not isinstance(raw, dict) or not raw:
        raise BundleMetadataError(f"{path}: expected a non-empty object of bundle -> names")
    assignments: dict[str, str] = {}
    for bundle, names in raw.items():
        if not bundle:
            raise BundleMetadataError(f"{path}: empty bundle name")
        if not isinstance(names, list):
            raise BundleMetadataError(f"{path}: {bundle!r} must map to a list of names")
        for name in names:
            if not isinstance(name, str) or not name:
                raise BundleMetadataError(
                    f"{path}: {bundle!r} contains an empty or non-string name"
                )
            if name in assignments:
                raise BundleMetadataError(f"{path}: {name!r} is assigned to more than one bundle")
            assignments[name] = bundle
    return assignments


def builtin_names() -> set[str]:
    return set(all_blueprints) | set(all_modules)


def is_external_name(name: str) -> bool:
    """External blueprints are addressed as ``<distribution>.<name>``."""
    return "." in name


def bundles_for(names: Iterable[str], assignments: dict[str, str] | None = None) -> list[str]:
    """The sorted set of bundles the built-in ``names`` need.

    Raises ``UnknownNameError`` for a name that is not built in and ``BundleMetadataError``
    for a registered name without an assignment. Unknown never means "no dependencies".
    """
    if assignments is None:
        assignments = load_assignments()
    known = builtin_names()
    bundles: set[str] = set()
    for name in names:
        if name in assignments:
            bundles.add(assignments[name])
        elif name in known:
            raise BundleMetadataError(f"{name!r} is registered but has no bundle in {BUNDLES_PATH}")
        else:
            raise UnknownNameError(unknown_name_message(name, known))
    return sorted(bundles)


def unknown_name_message(name: str, known: Iterable[str]) -> str:
    message = f"Unknown blueprint or module: {name!r}"
    suggestions = difflib.get_close_matches(name, sorted(known), n=5, cutoff=0.4)
    if suggestions:
        message += f". Did you mean: {', '.join(suggestions)}?"
    return message


def lock_path(bundle: str, backend: str) -> Path:
    """The exported lockfile of one bundle and backend.

    uv accepts only the PEP 751 names: ``pylock.<name>.toml`` with no dot inside ``<name>``.
    """
    return LOCKS_DIR / f"pylock.{bundle}-{backend}.toml"
