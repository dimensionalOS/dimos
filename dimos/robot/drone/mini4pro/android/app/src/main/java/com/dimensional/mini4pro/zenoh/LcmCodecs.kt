/**
 * `diagnostic_msgs.DiagnosticStatus` — `int32 values_length, int8 level, string name, string
 * message, string hardware_id, KeyValue values[]`.
 *
 * **The length field comes first, ahead of `level`**, because that is where lcm-gen hoisted it in
 * the `.lcm` declaration — not next to the array. Getting that wrong produces bytes that decode as
 * something plausible and wrong, which is why the fixture in `android/app/src/test/resources/lcm/`
 * is generated by DiMOS's own bindings rather than by this file.
 */
object DiagnosticStatusCodec : LcmCodec<LcmDiagnosticStatus> {
    override val typeName = "diagnostic_msgs.DiagnosticStatus"
    override val fingerprint = LcmFingerprints.DIAGNOSTIC_MSGS_DIAGNOSTIC_STATUS

    override fun encodeInto(w: LcmWriter, value: LcmDiagnosticStatus) {
        w.writeInt(value.values.size)
        w.writeByte(value.level.toInt())
        w.writeString(value.name)
        w.writeString(value.message)
        w.writeString(value.hardwareId)
        for (kv in value.values) KeyValueCodec.encodeInto(w, kv)
    }

    override fun decodeFrom(r: LcmReader): LcmDiagnosticStatus {
        val count = r.readInt()
        if (count < 0) throw LcmDecodeException("$typeName: negative values_length $count")
        val level = r.readByte()
        val name = r.readString()
        val message = r.readString()
        val hardwareId = r.readString()
        val values = ArrayList<LcmKeyValue>(minOf(count, 1024))
        for (i in 0 until count) values.add(KeyValueCodec.decodeFrom(r))
        return LcmDiagnosticStatus(level, name, message, hardwareId, values)
    }
}

