/**
 * `builtin_interfaces.Time` — `int32 sec, int32 nanosec`.
 *
 * Byte-identical to [TimeCodec] and a different type: the second field is `nanosec` rather than
 * `nsec`, so the fingerprints differ even though nothing on the wire does. It is nested by exactly
 * one type in this catalogue, [CompressedVideoCodec], and that is the only reason it exists.
 */
object BuiltinTimeCodec : LcmCodec<LcmTime> {
    override val typeName = "builtin_interfaces.Time"
    override val fingerprint = LcmFingerprints.BUILTIN_INTERFACES_TIME

    override fun encodeInto(w: LcmWriter, value: LcmTime) {
        w.writeInt(value.sec)
        w.writeInt(value.nsec)
    }

    override fun decodeFrom(r: LcmReader) = LcmTime(r.readInt(), r.readInt())
}

