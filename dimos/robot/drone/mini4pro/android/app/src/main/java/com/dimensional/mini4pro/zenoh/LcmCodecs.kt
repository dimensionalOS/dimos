/**
 * `foxglove_msgs.CompressedVideo` — **`int32 data_length`, `builtin_interfaces.Time`,
 * `string frame_id`, the bytes, `string format`.**
 *
 * Note the shape: unlike every other variable-length type here the length is the *first* field
 * and the body sits in the middle, between two strings. And unlike every other type here the
 * body is the aircraft's own H.264 and is copied rather than converted — see
 * [LcmCompressedVideo].
 */
object CompressedVideoCodec : LcmCodec<LcmCompressedVideo> {
    override val typeName = "foxglove_msgs.CompressedVideo"
    override val fingerprint = LcmFingerprints.FOXGLOVE_MSGS_COMPRESSED_VIDEO

    override fun encodeInto(w: LcmWriter, value: LcmCompressedVideo) {
        w.writeInt(value.data.size)
        BuiltinTimeCodec.encodeInto(w, value.timestamp)
        w.writeString(value.frameId)
        w.writeBytes(value.data)
        w.writeString(value.format)
    }

    override fun decodeFrom(r: LcmReader): LcmCompressedVideo {
        val length = r.readInt()
        if (length < 0) throw LcmDecodeException("$typeName: negative data_length $length")
        val timestamp = BuiltinTimeCodec.decodeFrom(r)
        val frameId = r.readString()
        val data = r.readBytes(length)
        return LcmCompressedVideo(timestamp, frameId, data, r.readString())
    }

    /**
     * A complete payload, written **straight out of a caller's buffer** at `[offset, offset+length)`.
     *
     * The video path's entry point, and the reason it exists is one allocation per frame. MSDK
     * delivers an access unit as a window into a buffer it reuses, and the obvious shape —
     * `copyOfRange` into an [LcmCompressedVideo], then encode — copies ~17 kB twice at 43 fps, so
     * 1.46 MB/s of memcpy on the thread that is decoding video. **The LCM message *is* the copy**:
     * `writeBytes` puts the bytes into a buffer this call owns, before it returns, so the caller's
     * array is free the moment it does. One copy, not two, and no 17 kB garbage per frame.
     *
     * The caller's contract is `video/RawFrameSink`'s: the buffer is valid for the duration of the
     * call and no longer. That is satisfied here by construction rather than by discipline.
     */
    fun encodeSlice(
        timestamp: LcmTime,
        frameId: String,
        data: ByteArray,
        offset: Int,
        length: Int,
        format: String,
    ): ByteArray {
        val w = LcmWriter(encodedSize(length, frameId, format))
        w.writeFingerprint(fingerprint)
        w.writeInt(length)
        BuiltinTimeCodec.encodeInto(w, timestamp)
        w.writeString(frameId)
        w.writeBytes(data, offset, length)
        w.writeString(format)
        return w.toByteArray()
    }

    /**
     * The encoded size of a frame carrying [dataLength] bytes, without encoding it.
     *
     * Exists so the video path can price a message before deciding to build one, so [encodeSlice]
     * can size its buffer exactly and never grow it, and so the bandwidth arithmetic in
     * `docs/measurements/` is computed from the codec rather than estimated beside it.
     */
    fun encodedSize(dataLength: Int, frameId: String, format: String): Int =
        LcmWire.FINGERPRINT_BYTES +
            4 + // data_length
            8 + // builtin_interfaces.Time
            4 + frameId.toByteArray(Charsets.UTF_8).size + 1 +
            dataLength +
            4 + format.toByteArray(Charsets.UTF_8).size + 1
}

