/**
 * `sensor_msgs.BatteryState` — the `battery` channel.
 *
 * **Both cell-array lengths are written before the header**, in declaration
 * order: `cell_voltage_length`, then `cell_temperature_length`, then everything
 * else. The array *bodies* come much later, after the `present` flag. Two
 * separated halves of the same field is the shape lcm-gen produces and the shape
 * the fixture proves.
 */
object BatteryStateCodec : LcmCodec<LcmBatteryState> {
    override val typeName = "sensor_msgs.BatteryState"
    override val fingerprint = LcmFingerprints.SENSOR_MSGS_BATTERY_STATE

    override fun encodeInto(w: LcmWriter, value: LcmBatteryState) {
        w.writeInt(value.cellVoltage.size)
        w.writeInt(value.cellTemperature.size)
        HeaderCodec.encodeInto(w, value.header)
        w.writeFloat(value.voltage)
        w.writeFloat(value.temperature)
        w.writeFloat(value.current)
        w.writeFloat(value.charge)
        w.writeFloat(value.capacity)
        w.writeFloat(value.designCapacity)
        w.writeFloat(value.percentage)
        w.writeByte(value.powerSupplyStatus.toInt())
        w.writeByte(value.powerSupplyHealth.toInt())
        w.writeByte(value.powerSupplyTechnology.toInt())
        w.writeBoolean(value.present)
        for (v in value.cellVoltage) w.writeFloat(v)
        for (v in value.cellTemperature) w.writeFloat(v)
        w.writeString(value.location)
        w.writeString(value.serialNumber)
    }

    override fun decodeFrom(r: LcmReader): LcmBatteryState {
        val cellVoltageLength = r.readInt()
        val cellTemperatureLength = r.readInt()
        if (cellVoltageLength < 0 || cellTemperatureLength < 0) {
            throw LcmDecodeException(
                "$typeName: negative cell array length ($cellVoltageLength, $cellTemperatureLength)"
            )
        }
        val header = HeaderCodec.decodeFrom(r)
        val voltage = r.readFloat()
        val temperature = r.readFloat()
        val current = r.readFloat()
        val charge = r.readFloat()
        val capacity = r.readFloat()
        val designCapacity = r.readFloat()
        val percentage = r.readFloat()
        val status = r.readByte()
        val health = r.readByte()
        val technology = r.readByte()
        val present = r.readBoolean()
        val cellVoltage = ArrayList<Float>(minOf(cellVoltageLength, 1024))
        for (i in 0 until cellVoltageLength) cellVoltage.add(r.readFloat())
        val cellTemperature = ArrayList<Float>(minOf(cellTemperatureLength, 1024))
        for (i in 0 until cellTemperatureLength) cellTemperature.add(r.readFloat())
        return LcmBatteryState(
            header = header,
            voltage = voltage,
            temperature = temperature,
            current = current,
            charge = charge,
            capacity = capacity,
            designCapacity = designCapacity,
            percentage = percentage,
            powerSupplyStatus = status,
            powerSupplyHealth = health,
            powerSupplyTechnology = technology,
            present = present,
            cellVoltage = cellVoltage,
            cellTemperature = cellTemperature,
            location = r.readString(),
            serialNumber = r.readString(),
        )
    }
}

