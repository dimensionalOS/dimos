/**
 * `sensor_msgs.CameraInfo` — **`D_length` before the header, and `height` before `width`.**
 *
 * Two orderings nobody expects, both lcm-gen's and both pinned by a fixture. The `D` *body* is
 * written after `distortion_model`, far from its own length — the same split-in-two shape
 * [BatteryStateCodec] has, and for the same reason.
 */
object CameraInfoCodec : LcmCodec<LcmCameraInfo> {
    override val typeName = "sensor_msgs.CameraInfo"
    override val fingerprint = LcmFingerprints.SENSOR_MSGS_CAMERA_INFO

    override fun encodeInto(w: LcmWriter, value: LcmCameraInfo) {
        w.writeInt(value.d.size)
        HeaderCodec.encodeInto(w, value.header)
        w.writeInt(value.height)
        w.writeInt(value.width)
        w.writeString(value.distortionModel)
        for (v in value.d) w.writeDouble(v)
        w.writeCovariance(value.k, MATRIX_SIZE_9, "$typeName.K")
        w.writeCovariance(value.r, MATRIX_SIZE_9, "$typeName.R")
        w.writeCovariance(value.p, MATRIX_SIZE_12, "$typeName.P")
        w.writeInt(value.binningX)
        w.writeInt(value.binningY)
        RegionOfInterestCodec.encodeInto(w, value.roi)
    }

    override fun decodeFrom(r: LcmReader): LcmCameraInfo {
        val dLength = r.readInt()
        if (dLength < 0) throw LcmDecodeException("$typeName: negative D_length $dLength")
        val header = HeaderCodec.decodeFrom(r)
        val height = r.readInt()
        val width = r.readInt()
        val model = r.readString()
        val d = ArrayList<Double>(minOf(dLength, 1024))
        for (i in 0 until dLength) d.add(r.readDouble())
        return LcmCameraInfo(
            header = header,
            height = height,
            width = width,
            distortionModel = model,
            d = d,
            k = r.readCovariance(MATRIX_SIZE_9),
            r = r.readCovariance(MATRIX_SIZE_9),
            p = r.readCovariance(MATRIX_SIZE_12),
            binningX = r.readInt(),
            binningY = r.readInt(),
            roi = RegionOfInterestCodec.decodeFrom(r),
        )
    }
}

