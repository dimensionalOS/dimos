        TwistWithCovarianceCodec.encodeInto(w, value.twist)
    }

    override fun decodeFrom(r: LcmReader) = LcmOdometry(
        HeaderCodec.decodeFrom(r),
        r.readString(),
        PoseWithCovarianceCodec.decodeFrom(r),
        TwistWithCovarianceCodec.decodeFrom(r),
    )
}

/**
 * `nav_msgs.Path` — **`int32 poses_length` first, then `header`, then the poses.**
 *
 * The length before the header is lcm-gen's hoisting of the array size field, not
 * a mistake: the `.lcm` struct declares `poses_length` ahead of everything it
 * sizes. Getting this backwards produces a message that decodes as a `Path` with
 * an absurd pose count, which is why it has its own fixture.
 */
object PathCodec : LcmCodec<LcmPath> {
    override val typeName = "nav_msgs.Path"
    override val fingerprint = LcmFingerprints.NAV_MSGS_PATH

    override fun encodeInto(w: LcmWriter, value: LcmPath) {
        w.writeInt(value.poses.size)
        HeaderCodec.encodeInto(w, value.header)
        for (p in value.poses) PoseStampedCodec.encodeInto(w, p)
    }

    override fun decodeFrom(r: LcmReader): LcmPath {
        val count = r.readInt()
        if (count < 0) throw LcmDecodeException("$typeName: negative poses_length $count")
        val header = HeaderCodec.decodeFrom(r)
        val poses = ArrayList<LcmPoseStamped>(minOf(count, 1024))
        for (i in 0 until count) poses.add(PoseStampedCodec.decodeFrom(r))
        return LcmPath(header, poses)
    }
}

