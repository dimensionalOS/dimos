package com.dimensional.mini4pro.zenoh

/**
 * One codec per LCM type, both directions.
 *
 * The types are those in `docs/zenoh-topics.md` and everything they nest. Each
 * codec knows three things: its package-qualified name (which is part of the
 * Zenoh key — `<prefix>/<channel>/<pkg>.<Type>`), its pinned fingerprint, and how
 * to move its fields.
 *
 * ## Nested versus top-level
 *
 * [encodeInto] and [decodeFrom] handle the **body only**: nested LCM structs are
 * inlined with no fingerprint of their own. [encode] and [decode] are the
 * top-level pair, and they are the only place the 8-byte prefix is written or
 * checked. Composing a codec inside another therefore always uses the `Into`/
 * `From` pair — the fingerprint appears exactly once, at the front of a payload.
 *
 * ## Field order is the wire order, and it is not always the ROS order
 *
 * Several types put a field first that no reader expects there, because lcm-gen
 * hoists variable-array length fields to the front of the struct:
 *
 * - [PathCodec] writes `poses_length` **before** `header`.
 * - [BatteryStateCodec] writes `cell_voltage_length` and
 *   `cell_temperature_length` **before** `header`.
 * - [CameraInfoCodec] writes `D_length` **before** `header`, and `height`
 *   before `width`.
 * - [Detection3DCodec] writes `results_length` **before** `header`, and is the
 *   only one with fields *after* its array.
 * - [Detection3DArrayCodec] writes `detections_length` **before** `header`, and
 *   carries a [Detection3DCodec] inside each element — two hoisted lengths on
 *   one wire, nested.
 *
 * Every one is confirmed byte-for-byte against fixtures generated by DiMOS's own
 * Python (`android/app/src/test/resources/lcm/`, from `tools/lcmfixtures/`).
 */
interface LcmCodec<T> {
    /** Package-qualified, exactly as it appears in a Zenoh key: `nav_msgs.Odometry`. */
    val typeName: String

    /** The pinned 8-byte fingerprint from [LcmFingerprints]. */
    val fingerprint: Long

    /** Writes the body — no fingerprint. This is what nesting uses. */
    fun encodeInto(w: LcmWriter, value: T)

    /** Reads the body — no fingerprint. This is what nesting uses. */
    fun decodeFrom(r: LcmReader): T

    /** A complete payload: fingerprint then body. What goes on the wire. */
    fun encode(value: T): ByteArray {
        val w = LcmWriter()
        w.writeFingerprint(fingerprint)
        encodeInto(w, value)
        return w.toByteArray()
    }

    /**
     * A complete payload, checked. Throws [LcmDecodeException] on a wrong
     * fingerprint, a truncated body, or trailing bytes — all three mean the
     * sender is not speaking the type we think, and a partial decode of a
     * command is worse than no command.
     */
    fun decode(bytes: ByteArray): T {
        val r = LcmReader(bytes)
        r.expectFingerprint(fingerprint, typeName)
        val value = decodeFrom(r)
        if (r.remaining != 0) {
            throw LcmDecodeException("$typeName: ${r.remaining} trailing bytes after a complete message")
        }
        return value
    }
}

/** Writes a fixed-size covariance, refusing a list of the wrong length. */
private fun LcmWriter.writeCovariance(values: List<Double>, size: Int, what: String) {
    require(values.size == size) { "$what: covariance must be $size doubles, got ${values.size}" }
    for (v in values) writeDouble(v)
}

private fun LcmReader.readCovariance(size: Int): List<Double> {
    val out = ArrayList<Double>(size)
    for (i in 0 until size) out.add(readDouble())
    return out
}

