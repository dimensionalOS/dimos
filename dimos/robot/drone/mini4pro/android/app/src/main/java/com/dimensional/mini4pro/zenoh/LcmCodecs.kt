/**
 * `vision_msgs.Detection3D` — **`int32 results_length` first, then `header`, then the
 * hypotheses, then `bbox`, then `id`.**
 *
 * The third type in this file whose length field is hoisted ahead of the header, and the only one
 * with fields *after* the array: a length that disagreed with the list would not truncate the
 * message, it would decode `bbox` out of the tail of a hypothesis and `id` out of `bbox`. Which
 * is why the count is derived from [LcmDetection3D.results] here and is not a field there.
 */
object Detection3DCodec : LcmCodec<LcmDetection3D> {
    override val typeName = "vision_msgs.Detection3D"
    override val fingerprint = LcmFingerprints.VISION_MSGS_DETECTION_3D

    override fun encodeInto(w: LcmWriter, value: LcmDetection3D) {
        w.writeInt(value.results.size)
        HeaderCodec.encodeInto(w, value.header)
        for (r in value.results) ObjectHypothesisWithPoseCodec.encodeInto(w, r)
        BoundingBox3DCodec.encodeInto(w, value.bbox)
        w.writeString(value.id)
    }

    override fun decodeFrom(r: LcmReader): LcmDetection3D {
        val count = r.readInt()
        if (count < 0) throw LcmDecodeException("$typeName: negative results_length $count")
        val header = HeaderCodec.decodeFrom(r)
        val results = ArrayList<LcmObjectHypothesisWithPose>(minOf(count, 1024))
        for (i in 0 until count) results.add(ObjectHypothesisWithPoseCodec.decodeFrom(r))
        return LcmDetection3D(header, results, BoundingBox3DCodec.decodeFrom(r), r.readString())
    }
}

