/**
 * `tf2_msgs.TFMessage` — **`int32 transforms_length` then the edges, and no header at all.**
 *
 * The type is the array. Unlike [PathCodec] there is nothing after the length but the elements,
 * so a length written from anywhere other than the list would produce a message that decodes into
 * a truncated or over-read tree — which is why the count is derived here and is not a field.
 */
object TfMessageCodec : LcmCodec<LcmTfMessage> {
    override val typeName = "tf2_msgs.TFMessage"
    override val fingerprint = LcmFingerprints.TF2_MSGS_TF_MESSAGE

    override fun encodeInto(w: LcmWriter, value: LcmTfMessage) {
        w.writeInt(value.transforms.size)
        for (t in value.transforms) TransformStampedCodec.encodeInto(w, t)
    }

    override fun decodeFrom(r: LcmReader): LcmTfMessage {
        val count = r.readInt()
        if (count < 0) throw LcmDecodeException("$typeName: negative transforms_length $count")
        val out = ArrayList<LcmTransformStamped>(minOf(count, 1024))
        for (i in 0 until count) out.add(TransformStampedCodec.decodeFrom(r))
        return LcmTfMessage(out)
    }
}

