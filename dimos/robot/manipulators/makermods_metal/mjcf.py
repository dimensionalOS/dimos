"""The Metal in MuJoCo: its MJCF from the pinned URDF, and the bench it stands on.

Run ``python -m dimos.robot.manipulators.makermods_metal.mjcf`` to rewrite
``assets/metal.xml`` after changing anything here.
"""

from __future__ import annotations

import math
from pathlib import Path
from typing import Any
import xml.etree.ElementTree as ET

import mujoco
import numpy as np

from dimos.robot.manipulators.makermods_metal.config import (
    METAL,
    METAL_ARM_JOINTS,
    METAL_BENCH_OBJECTS,
    METAL_BENCH_PATH,
    METAL_FINGER_JOINTS,
    METAL_JOINT3_LIMITS,
    METAL_KD,
    METAL_KP,
    METAL_MESHDIR,
    METAL_MJCF_PATH,
    METAL_SIM_HOME,
    METAL_URDF,
    metal_sim_joints,
)
from dimos.simulation.engines.robot_sim_binding import RobotSimSpec

#: Motor rotor inertia felt at each arm joint, kg m^2: DM-J4340-class motors on
#: the three big joints, DM-J4310-class on the wrist.
METAL_ARMATURE = (0.032, 0.032, 0.032, 0.0018, 0.0018, 0.0018)
#: Jaw actuator gains, N/m and N s/m; the URDF's 3 N effort limit caps its force.
METAL_GRIPPER_KP = 400.0
METAL_GRIPPER_KV = 10.0
METAL_TIMESTEP = 0.002
#: The wrist camera's MJCF name, where it sits on gripper_base, metres, and how
#: far it leans from the finger axis toward the gripper's own axis, degrees.
METAL_CAMERA_NAME = "wrist_camera"
METAL_CAMERA_POS = (0.07, 0.0, -0.03)
METAL_CAMERA_TILT_DEG = 20.0
METAL_CAMERA_FOVY_DEG = 60.0
#: The bench's fixed camera in ``assets/bench.xml``, which sees the whole bench.
METAL_SCENE_CAMERA_NAME = "scene_camera"
_GENERATED_NOTE = (
    "<!-- Generated by python -m dimos.robot.manipulators.makermods_metal.mjcf from the "
    "pinned Metal URDF; edit mjcf.py, not this file. Meshes are named by file: compile "
    "with meshdir set to the pinned description's meshes directory. -->\n"
)

#: Finds the Metal's joints in a composed scene by name, so the bench's free
#: bodies may come before it in the model without being taken for its base.
METAL_SIM_SPEC = RobotSimSpec(
    robot_id="metal",
    hardware_joints=tuple(metal_sim_joints()),
    model_joint_names=(*METAL_ARM_JOINTS, METAL_FINGER_JOINTS[0]),
)


def metal_mjcf_spec() -> mujoco.MjSpec:
    """The Metal arm, jaw and wrist camera as a MuJoCo spec, built from the pinned URDF.

    Meshes are named by file only: set ``meshdir`` or ``modelfiledir`` to
    ``METAL_MESHDIR`` before compiling. Reading the URDF clones the pinned
    Metal description on first use.
    """
    urdf = Path(METAL_URDF).read_text()
    spec = mujoco.MjSpec.from_string(urdf.replace("package://metal_description/meshes/", ""))
    spec.modelname = "metal"  # type: ignore[attr-defined]
    # Keep base_link and gripper_base as bodies instead of folding them into
    # their parents: the planner, the camera and the hardware name them.
    spec.compiler.fusestatic = False
    # Actuator damping is integrated implicitly, so the stiff wrist stays stable.
    spec.option.integrator = mujoco.mjtIntegrator.mjINT_IMPLICITFAST  # type: ignore[attr-defined]
    spec.option.timestep = METAL_TIMESTEP
    spec.joint("joint3").range = list(METAL_JOINT3_LIMITS)
    # Gravity compensation follows the hardware: with it off, the sim arm sags
    # under its own weight by the gravity torque over kp, as the real arm does.
    for body in spec.bodies:
        if body.name != "base_link":
            body.gravcomp = float(METAL.gravity)
    for name, armature, kp, kd in zip(
        METAL_ARM_JOINTS, METAL_ARMATURE, METAL_KP, METAL_KD, strict=True
    ):
        spec.joint(name).armature = armature
        _add_position_actuator(spec, name, name, kp, kd, tuple(spec.joint(name).range))
    driven, follower = METAL_FINGER_JOINTS
    _add_position_actuator(
        spec,
        "gripper",
        driven,
        METAL_GRIPPER_KP,
        METAL_GRIPPER_KV,
        tuple(spec.joint(driven).range),
    )
    mimics = _urdf_mimics(urdf)
    if follower not in mimics:
        raise ValueError(f"{METAL_URDF.name}: {follower} does not mimic {driven}")
    for mimic, (leader, multiplier, offset) in mimics.items():
        equality = spec.add_equality(
            type=mujoco.mjtEq.mjEQ_JOINT,  # type: ignore[attr-defined]
            name1=mimic,
            name2=leader,
        )
        equality.data[:2] = [offset, multiplier]
    # The closed fingers touch, and link1 turns inside the base, which MuJoCo
    # counts as part of the world since nothing moves it.
    spec.add_exclude(bodyname1="link7", bodyname2="link8")
    spec.add_exclude(bodyname1="base_link", bodyname2="link1")
    _add_wrist_camera(spec.body("gripper_base"))
    return spec


def write_metal_mjcf(path: Path) -> None:
    """Save the Metal MJCF at ``path``, with its meshes named by file (see ``metal_mjcf_spec``)."""
    spec = metal_mjcf_spec()
    # Resolves the meshes for this compile; MuJoCo does not write it out.
    spec.modelfiledir = str(METAL_MESHDIR)  # type: ignore[attr-defined]
    spec.compile()
    path.write_text(_GENERATED_NOTE + spec.to_xml())


def make_metal_sim_module_kwargs() -> dict[str, Any]:
    """MujocoSimModule settings for one Metal on the bench.

    The arm MJCF takes its meshes from the pinned description at run time, the
    bench is the scene, and the three bench objects are reported on
    ``body_poses``. The bench top is the world's z = 0 and the arm's base_link
    sits on it at the origin, so the planner needs no base pose. Rays from the
    wrist camera (80 x 60, about 1 cm apart on the bench) give world-frame
    points at 5 Hz on ``pointcloud``. The bench's fixed camera shows the whole
    bench on ``scene_image``.
    """
    return {
        "robot_mjcf": METAL_MJCF_PATH,
        "robot_meshdir": METAL_MESHDIR,
        "scene_xml": METAL_BENCH_PATH,
        "robot_sim_spec": METAL_SIM_SPEC,
        "dof": len(METAL_ARM_JOINTS),
        "camera_name": METAL_CAMERA_NAME,
        "scene_camera": METAL_SCENE_CAMERA_NAME,
        # The sim knows the camera's world pose exactly, so its frames hang off world.
        "base_frame_id": "world",
        "reset_joint_positions": list(METAL_SIM_HOME),
        "tracked_bodies": list(METAL_BENCH_OBJECTS),
        "enable_pointcloud": True,
        "enable_mujoco_lidar": True,
        "mujoco_lidar_raycast_width": 80,
        "mujoco_lidar_raycast_height": 60,
        "mujoco_lidar_voxel_size": 0.01,
    }


def _add_position_actuator(
    spec: mujoco.MjSpec,
    name: str,
    joint: str,
    kp: float,
    kv: float,
    ctrlrange: tuple[float, float],
) -> None:
    actuator = spec.add_actuator(name=name, target=joint, trntype=mujoco.mjtTrn.mjTRN_JOINT)
    actuator.set_to_position(kp=kp, kv=kv)
    actuator.ctrllimited = mujoco.mjtLimited.mjLIMITED_TRUE  # type: ignore[attr-defined]
    actuator.ctrlrange = list(ctrlrange)


def _urdf_mimics(urdf: str) -> dict[str, tuple[str, float, float]]:
    """Each mimicking joint's (joint it follows, multiplier, offset) from the URDF."""
    mimics: dict[str, tuple[str, float, float]] = {}
    for joint in ET.fromstring(urdf).iter("joint"):
        mimic = joint.find("mimic")
        if mimic is not None:
            mimics[joint.attrib["name"]] = (
                mimic.attrib["joint"],
                float(mimic.attrib.get("multiplier", 1.0)),
                float(mimic.attrib.get("offset", 0.0)),
            )
    return mimics


def _add_wrist_camera(gripper_base: mujoco.MjsBody) -> None:  # type: ignore[name-defined]
    # In gripper_base, the fingers run along +z and slide along y; the body
    # itself spans x up to 0.035 m, so the camera sits just off its +x face.
    # A MuJoCo camera looks along its -z with +y up: tilt -z from the finger
    # axis toward -x so the fingertips and the bench beyond share the frame.
    tilt = math.radians(METAL_CAMERA_TILT_DEG)
    axes = np.array(
        [
            [math.cos(tilt), 0.0, math.sin(tilt)],
            [0.0, -1.0, 0.0],
            [math.sin(tilt), 0.0, -math.cos(tilt)],
        ]
    )
    quat = np.zeros(4)
    mujoco.mju_mat2Quat(quat, axes.flatten())  # type: ignore[attr-defined]
    gripper_base.add_camera(
        name=METAL_CAMERA_NAME,
        pos=list(METAL_CAMERA_POS),
        quat=quat.tolist(),
        fovy=METAL_CAMERA_FOVY_DEG,
    )


if __name__ == "__main__":
    write_metal_mjcf(METAL_MJCF_PATH)
